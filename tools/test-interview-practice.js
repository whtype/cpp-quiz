var assert=require('assert'),I=require('../utils/interview')
var now=1000000000,day=86400000,cards=[
{id:'a',course:'arrays'},{id:'b',course:'arrays'},{id:'c',course:'arrays'},{id:'d',course:'exceptions'}]
var state={records:{a:{grade:2,reviewedAt:now-day,dueAt:now+day,attempts:1},b:{grade:0,reviewedAt:1,dueAt:now-day,attempts:1}},sessions:{}}
I.open(cards,state,'arrays',now)
assert.deepStrictEqual(state.sessions.arrays.ids,['b','c'],'due first, new next, no premature repeat')
assert.strictEqual(I.rate(cards,state,'b',2,now),false,'cannot grade before revealing')
I.draft(cards,state,'b','vector<int> result;')
I.reveal(cards,state,'b')
assert.ok(I.rate(cards,state,'b',1,now));assert.strictEqual(state.records.b.dueAt,now+3*day)
assert.strictEqual(I.rate(cards,state,'b',2,now),false,'stale double click does not grade next question')
assert.strictEqual(state.records.b.attempts,2)
I.draft(cards,state,'c','array answer')
I.open(cards,state,'exceptions',now);I.draft(cards,state,'d','try / catch')
I.open(cards,state,'arrays',now)
assert.strictEqual(I.view(cards,state,now).draft,'array answer');assert.strictEqual(I.view(cards,state,now).card.id,'c')
var restored=JSON.parse(JSON.stringify(state));I.open(cards,restored,'arrays',now)
assert.strictEqual(I.view(cards,restored,now).draft,'array answer')
I.reveal(cards,restored,'c');I.rate(cards,restored,'c',2,now)
assert.ok(I.view(cards,restored,now).completed);assert.strictEqual(restored.records.c.dueAt,now+7*day)
I.open(cards,restored,'arrays',now,true);assert.ok(I.view(cards,restored,now).card)
I.open(cards,restored,'exceptions',now);I.reveal(cards,restored,'d');I.rate(cards,restored,'d',0,now)
assert.strictEqual(restored.records.d.dueAt,now+day)
I.open(cards,restored,'invalid',now);assert.strictEqual(restored.course,'')
var removed=cards.filter(function(c){return c.id!=='b'});I.open(removed,state,'arrays',now)
assert.ok(state.sessions.arrays.ids.indexOf('b')<0,'invalid stored IDs rebuild safely')
assert.strictEqual(I.summary(cards,restored.records,'exceptions',now+day).due,1)
var many=Array.from({length:12},function(_,i){return {id:'m'+i,course:'arrays'}}),s={};I.open(many,s,'',now);assert.strictEqual(s.sessions.all.ids.length,5)
console.log('PASS self-test: due order, no premature repeats, rating guards, intervals, drafts, chapter isolation, reload, obsolete IDs, 5-card cap')

I.open(cards,restored,'exceptions',now+day)
assert.strictEqual(I.view(cards,restored,now+day).completed,false,'completed session must reopen due cards on a later visit')
var bank=require('../data/interview-cards'),L=require('../utils/learning')
assert.strictEqual(bank.length,24);assert.strictEqual(new Set(bank.map(function(q){return q.id})).size,24)
L.COURSES.filter(function(c){return c.key}).forEach(function(c){assert.strictEqual(bank.filter(function(q){return q.course===c.key}).length,2)})
bank.forEach(function(q){
  assert.ok(q.title&&q.prompt&&q.points.length>=3&&q.pitfalls.length&&q.followUp)
  assert.ok(/^https:\/\//.test(q.reference.url))
  if(q.kind==='手写')assert.ok(q.solution&&q.checks.length>=3&&q.starter)
})
console.log('PASS interview content structure: 24 unique cards, 12 chapters, prompts/rubrics/references/handwritten cases')
